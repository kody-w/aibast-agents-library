def _learn_source(value: str) -> bool:
    if any(character.isspace() for character in value):
        return False
    try:
        parsed = urlsplit(value)
    except ValueError:
        return False
    path = parsed.path
    decoded_url = value
    for _ in range(4):
        decoded = unquote(path)
        next_url = unquote(decoded_url)
        if decoded == path and next_url == decoded_url:
            break
        path = decoded
        decoded_url = next_url
    return (
        parsed.scheme == "https" and parsed.netloc == "learn.microsoft.com"
        and path.startswith("/en-us/") and bool(path.removeprefix("/en-us/"))
        and ".." not in decoded_url and "\\" not in path
    )


def _note_text(value, location: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise RunbookSourceError(f"{NOTES}: {location} must be a non-empty string")
    if value.strip().casefold() in {"none", "null", "nan", "{}", "[]"}:
        raise RunbookSourceError(f"{NOTES}: {location} contains a sentinel string")


def _note_source(
    value, location: str, files: frozenset[str], root: Path = ROOT,
    anchor_cache: dict[str, set[str]] | None = None,
) -> None:
    _note_text(value, location)
    if value in files or _learn_source(value):
        return
    path, separator, fragment = value.partition("#")
    if not separator or path not in files:
        raise RunbookSourceError(f"{NOTES}: {location} has missing source or invalid source URL {value!r}")
    if not fragment:
        raise RunbookSourceError(f"{NOTES}: {location} has an empty source anchor: {value!r}")
    if not path.lower().endswith((".md", ".markdown", ".html", ".htm")):
        raise RunbookSourceError(f"{NOTES}: {location} source anchors require Markdown or HTML: {value!r}")
    cache = anchor_cache if anchor_cache is not None else {}
    if path not in cache:
        try:
            body = (root / path).read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise RunbookSourceError(f"{NOTES}: cannot read source anchors in {path}: {exc}") from exc
        cache[path] = _LINKS.anchors_of(body)
    if unquote(fragment).lower() not in cache[path]:
        raise RunbookSourceError(f"{NOTES}: {location} has missing source anchor {value!r}")


def _validate_notes(
    name: str, entry: dict, files: frozenset[str], patterns: dict, declared_systems=(), root: Path = ROOT,
) -> None:
    if entry.get("schema") != "aibast-runbook-notes/2.0" or entry.get("solution") != name:
        raise RunbookSourceError(f"{NOTES}: schema 2.0 and canonical solution {name} are required")
    string_lists = {"sources", "related_patterns"}
    record_lists = {
        "target_users": {"role", "need", "source"}, "what_goes_wrong": {"id", "issue", "response", "source"},
        "delivery_roles": {"role", "responsibility", "source"}, "prerequisites": {"item", "detail", "source"},
        "go_no_go": {"criterion", "threshold", "source"}, "boundary_tests": {"prompt", "expected", "source"},
        "design_decisions": {"decision", "reason", "source"},
        "production_hardening": {"area", "action", "owner", "phase", "source"},
        "data_contract": {"entity", "fields", "used_by", "system_of_record", "sensitivity", "source"},
        "integration_points": {"system", "purpose", "skills", "access", "template_provides", "customer_wires", "source"},
        "non_functional": {"area", "consideration", "source"},
        "state_and_recovery": {"condition", "behavior", "owner", "source"},
    }
    for field in ("scope_in", "scope_out", "qualification_checklist", "never_do"):
        record_lists[field] = {"text", "source"}
    objects = {
        "identity": {"auth", "audience", "least_privilege", "source"},
        "baseline": {"measure", "record_columns", "why", "source"},
    }
    array_fields = {"fields", "used_by", "skills", "least_privilege", "record_columns"}
    allowed = string_lists | record_lists.keys() | objects.keys() | {"phase_exit_criteria", "schema", "solution"}
    unknown = set(entry) - allowed
    if unknown:
        raise RunbookSourceError(f"{NOTES}: {name} has unknown fields: {', '.join(sorted(unknown))}")
    if not isinstance(entry.get("sources"), list) or not entry["sources"]:
        raise RunbookSourceError(f"{NOTES}: {name} requires a non-empty sources array")
    required = {
        "target_users", "scope_in", "scope_out", "qualification_checklist", "what_goes_wrong",
        "delivery_roles", "prerequisites", "phase_exit_criteria", "go_no_go", "boundary_tests",
        "design_decisions", "never_do", "production_hardening", "related_patterns", "sources",
    }
    if required - entry.keys():
        raise RunbookSourceError(f"{NOTES}: {name} has missing required notes fields: {', '.join(sorted(required - entry.keys()))}")
    anchor_cache: dict[str, set[str]] = {}

    def text(value, location):
        _note_text(value, location)
        if re.search(r"\d+(?:\.\d+)?\s*%|\$\s*\d|\b\d+(?:\.\d+)?\s*(?:hours?|days?|weeks?|months?|years?|minutes?)\b", value, re.I):
            raise RunbookSourceError(f"{NOTES}: {location} contains a percentage, duration or monetary figure")

    def record(item, keys, location):
        optional = {"id"} if location.endswith(".state_and_recovery") else set()
        if not isinstance(item, dict) or not keys <= set(item) or set(item) - keys - optional:
            raise RunbookSourceError(f"{NOTES}: {location} requires exactly {', '.join(sorted(keys))}")
        for key, value in item.items():
            field_location = location + "." + key
            if key == "source":
                _note_source(value, field_location, files, root, anchor_cache)
            elif key == "phase":
                if type(value) is not int or not 0 <= value <= 6:
                    raise RunbookSourceError(f"{NOTES}: {field_location} must be an integer from 0 to 6")
            elif key in array_fields or key == "audience" and isinstance(value, list):
                if not isinstance(value, list) or not value:
                    raise RunbookSourceError(f"{NOTES}: {field_location} must be a non-empty array")
                for member in value:
                    if key == "fields":
                        _note_text(member, field_location)
                    else:
                        text(member, field_location)
            else:
                text(value, field_location)

    for field, value in entry.items():
        if field in {"schema", "solution"}:
            continue
        if field == "phase_exit_criteria":
            phases = {f"phase_{index}" for index in range(7)}
            if not isinstance(value, dict) or set(value) != phases:
                raise RunbookSourceError(f"{NOTES}: {name}.{field} must contain phase_0 through phase_6")
            for phase, criteria in value.items():
                if not isinstance(criteria, list) or not criteria:
                    raise RunbookSourceError(f"{NOTES}: {name}.{field}.{phase} must be a nonempty list")
                for item in criteria:
                    record(item, {"text", "source"}, f"{name}.{field}.{phase}")
            continue
        if field in objects:
            record(value, objects[field], f"{name}.{field}")
            continue
        if not isinstance(value, list) or not value:
            raise RunbookSourceError(f"{NOTES}: {name}.{field} must be a nonempty list")
        for item in value:
            if field in record_lists:
                record(item, record_lists[field], f"{name}.{field}")
            elif field == "sources":
                _note_source(item, f"{name}.{field}", files, root, anchor_cache)
            else:
                _note_text(item, f"{name}.{field}")
    for field in ("what_goes_wrong", "state_and_recovery"):
        identifiers = [item["id"] for item in entry.get(field, []) if "id" in item]
        if any(not _SLUG.fullmatch(identifier) for identifier in identifiers) or len(set(identifiers)) != len(identifiers):
            raise RunbookSourceError(f"{NOTES}: {name}.{field} requires unique kebab-case identifiers")
    roles = {item["role"] for item in entry.get("delivery_roles", [])}
    for step in entry.get("production_hardening", []):
        if step["owner"] not in roles:
            raise RunbookSourceError(f"{NOTES}: {name}.production_hardening has unknown owner {step['owner']!r}")
    for state in entry.get("state_and_recovery", []):
        if state["owner"] not in roles | {"Template", "Customer or partner"}:
            raise RunbookSourceError(f"{NOTES}: {name}.state_and_recovery has unknown owner {state['owner']!r}")
    alm = [step["owner"] for step in entry["production_hardening"] if re.search(r"\bALM\b", step["area"], re.I)]
    approval = [step["owner"] for step in entry["production_hardening"] if re.search(r"\bapproval\b", step["area"], re.I)]
    if len(alm) != 1 or len(approval) != 1 or alm[0] == approval[0]:
        raise RunbookSourceError(f"{NOTES}: {name} requires separate ALM and approval owner roles")
    for point in entry.get("integration_points", []):
        if point["access"] not in {"read", "write", "read-write"}:
            raise RunbookSourceError(f"{NOTES}: {name}.integration_points has invalid access {point['access']!r}")
        if point["system"].casefold() not in {system.casefold() for system in declared_systems}:
            raise RunbookSourceError(f"{NOTES}: {name} has undeclared integration system {point['system']!r}")
    for identifier in entry.get("related_patterns", []):
        if identifier not in patterns:
            raise RunbookSourceError(f"{NOTES}: {name} has unknown related pattern {identifier!r}")


def _validate_vertical_names(root: Path, files: frozenset[str], used_categories=None) -> None:
    source = "index.html"
    if source not in files:
        raise RunbookSourceError("Missing vertical-label source: index.html CATEGORY_NAMES")
    text = (root / source).read_text(encoding="utf-8")
    match = re.search(r"\bconst\s+CATEGORY_NAMES\s*=\s*(\{.*?\});", text, re.S)
    if not match:
        raise RunbookSourceError("index.html: CATEGORY_NAMES object is missing")
    data = re.sub(r"(?m)^(\s*)([a-z][a-z0-9_]*):", r'\1"\2":', match[1])
    try:
        labels = json.loads(data)
    except ValueError as exc:
        raise RunbookSourceError(f"index.html: cannot parse CATEGORY_NAMES: {exc}") from exc
    used = set(VERTICAL_NAMES) if used_categories is None else set(used_categories)
    mismatches = sorted(category for category in used if labels.get(category) != VERTICAL_NAMES.get(category))
    if mismatches:
        raise RunbookSourceError(
            "VERTICAL_NAMES must agree with index.html CATEGORY_NAMES for used categories: " + ", ".join(mismatches)
        )


def normalize_journey_stage(value: str) -> tuple[str, str | None]:
    if not isinstance(value, str) or not value.strip():
        raise RunbookSourceError("journey_stage must be a non-empty string")
    primary, _, secondary = value.strip().partition(" and ")
    primary, secondary = primary.strip(), secondary.strip()
    if not primary:
        raise RunbookSourceError("journey_stage has no primary stage")
    return (
        primary[:1].upper() + primary[1:],
        secondary[:1].upper() + secondary[1:] if secondary else None,
    )


def _file_universe(root: Path) -> frozenset[str]:
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        capture_output=True, check=False,
    )
    if result.returncode:
        raise RunbookSourceError(
            "Cannot enumerate repository files with git ls-files: "
            + result.stderr.decode("utf-8", errors="replace").strip()
        )
    return frozenset(
        name for name in result.stdout.decode("utf-8").split("\0")
        if name and (root / name).is_file()
    )


def _json(root: Path, relative: str, files: frozenset[str], required: bool = False) -> dict:
    if relative not in files:
        if required:
            raise RunbookSourceError(f"Missing required source: {relative}")
        return {}
    try:
        value = json.loads((root / relative).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError) as exc:
        raise RunbookSourceError(f"Cannot read JSON source {relative}: {exc}") from exc
    if not isinstance(value, dict):
        raise RunbookSourceError(f"{relative}: expected a JSON object")
    return value


class Solution:
    def __init__(self, name: str, slug: str, copy: dict, agent: dict, deployment: dict):
        self.name = name
        self.slug = slug
        self.copy = copy
        self.agent = agent
        self.deployment = deployment
        self.package = f"solutions/{slug}"
        self.architecture_source = f"state/architecture_level2_sources/{name.rsplit('/', 1)[-1]}.json"
        self.demo_source = f"tests/demo_cases/{slug}.json"
        self.notes_source = f"{NOTES}/{slug}.json"
        self.stage, self.secondary_stage = normalize_journey_stage(copy.get("journey_stage"))

    @property
    def display_name(self) -> str:
        return _text(self.copy.get("display_name"), self.slug)

    @property
    def vertical(self) -> str:
        return VERTICAL_NAMES[self.agent["category"]]

    def path(self, relative: str) -> str:
        return f"{self.package}/{relative}"


class Library:
    def __init__(
        self, root: Path, files: frozenset[str], catalog: dict,
        solutions: dict[str, Solution], patterns: dict[str, dict], notes: dict,
    ):
        self.root = root
        self.files = files
        self.catalog = catalog
        self.solutions = solutions
        self.by_name = {solution.name: solution for solution in solutions.values()}
        self.patterns = patterns
        self.notes = notes
        self.directories = frozenset(
            str(parent) for name in files for parent in PurePosixPath(name).parents
            if str(parent) != "."
        )

    def exists(self, relative: str) -> bool:
        relative = relative.rstrip("/")
        return relative in self.files or relative in self.directories

    def json(self, relative: str, required: bool = False) -> dict:
        return _json(self.root, relative, self.files, required)

    def matching(self, pattern: str) -> list[str]:
        return sorted(name for name in self.files if fnmatch.fnmatchcase(name, pattern))


def load_library(root: Path = ROOT) -> Library:
    root = Path(root).resolve()
    files = _file_universe(root)
    catalog = _json(root, CATALOG, files, required=True).get("solutions")
    agents = _json(root, REGISTRY, files, required=True).get("agents")
    if not isinstance(catalog, dict) or not catalog:
        raise RunbookSourceError(f"{CATALOG}: solutions must be a non-empty object")
    if not isinstance(agents, list):
        raise RunbookSourceError(f"{REGISTRY}: agents must be an array")

    canonical_names = set()
    for name, copy in catalog.items():
        if (
            not name.startswith("@aibast-agents-library/")
            or not _SLUG.fullmatch(name.removeprefix("@aibast-agents-library/"))
            or not isinstance(copy, dict)
        ):
            raise RunbookSourceError(f"{CATALOG}: invalid canonical solution {name!r}")
        canonical_names.add(name.rsplit("/", 1)[-1])
    for name, slug in PACKAGE_ALIASES.items():
        if name not in canonical_names or name == slug or not _SLUG.fullmatch(slug):
            raise RunbookSourceError(f"Stale or invalid package alias: {name} -> {slug}")
    if len(set(PACKAGE_ALIASES.values())) != len(PACKAGE_ALIASES):
        raise RunbookSourceError("Package aliases must have distinct target folders")

    package_dirs = {
        name.split("/")[1] for name in files
        if name.startswith("solutions/") and name.count("/") >= 2
        and name.split("/")[1] not in {"_shared", RUNBOOK_NOTES_DIRECTORY}
    }
    for slug, reason in DRAFT_PACKAGES.items():
        if not isinstance(reason, str) or not reason.strip():
            raise RunbookSourceError(f"Draft package {slug} needs a non-empty reason")
        if slug not in package_dirs:
            raise RunbookSourceError(f"Stale draft allowlist entry: {slug} has no package")
        if slug in canonical_names or slug in PACKAGE_ALIASES.values():
            raise RunbookSourceError(f"Stale draft allowlist entry: {slug} is a catalog package")

    packages: dict[str, tuple[str, dict]] = {}
    for slug in sorted(package_dirs - DRAFT_PACKAGES.keys()):
        path = f"solutions/{slug}/deployment.json"
        if path not in files:
            raise RunbookSourceError(f"Orphan package solutions/{slug}: missing deployment.json")
        deployment = _json(root, path, files, required=True)
        name = deployment.get("name")
        if not isinstance(name, str) or name not in catalog:
            raise RunbookSourceError(f"Orphan package {path}: name {name!r} is not in {CATALOG}")
        if name in packages:
            raise RunbookSourceError(
                f"Duplicate package identity {name}: solutions/{packages[name][0]} and solutions/{slug}"
            )
        canonical = name.rsplit("/", 1)[-1]
        expected_slug = PACKAGE_ALIASES.get(canonical, canonical)
        if slug != expected_slug:
            raise RunbookSourceError(
                f"{path}: {name} must use package folder {expected_slug}; "
                "declare a necessary alias in PACKAGE_ALIASES"
            )
        packages[name] = (slug, deployment)

    solutions = {}
    for name, copy in sorted(catalog.items()):
        if name not in packages:
            expected = PACKAGE_ALIASES.get(name.rsplit("/", 1)[-1], name.rsplit("/", 1)[-1])
            raise RunbookSourceError(f"Missing package for {name}: solutions/{expected}/deployment.json")
        matches = [agent for agent in agents if isinstance(agent, dict) and agent.get("name") == name]
        if len(matches) != 1:
            raise RunbookSourceError(
                f"{REGISTRY}: expected exactly one agent named {name}; found {len(matches)}"
            )
        agent = matches[0]
        if not isinstance(agent.get("_solution"), dict):
            raise RunbookSourceError(f"{REGISTRY}: {name} has no _solution object")
        if agent.get("category") not in VERTICAL_NAMES:
            raise RunbookSourceError(f"{REGISTRY}: {name} has unknown category {agent.get('category')!r}")
        slug, deployment = packages[name]
        solution = Solution(name, slug, copy, agent, deployment)
        if solution.stage not in JOURNEY_STAGES:
            raise RunbookSourceError(
                f"{CATALOG}: {name} has unknown journey stage {solution.stage!r}"
            )
        solutions[slug] = solution
    for name, slug in PACKAGE_ALIASES.items():
        if slug not in solutions or solutions[slug].name != f"@aibast-agents-library/{name}":
            raise RunbookSourceError(f"Stale package alias: {name} -> {slug}")

    pattern_data = _json(root, PATTERNS, files, required=True)
    patterns = {}
    for group in ("aibast_patterns", "runbooks_patterns"):
        rows = pattern_data.get(group)
        if not isinstance(rows, list):
            raise RunbookSourceError(f"{PATTERNS}: {group} must be an array")
        for row in rows:
            if not isinstance(row, dict) or not isinstance(row.get("id"), str):
                raise RunbookSourceError(f"{PATTERNS}: every pattern needs a string id")
            identifier = row["id"]
            if identifier in patterns:
                raise RunbookSourceError(f"{PATTERNS}: duplicate pattern id {identifier}")
            if not row.get("title"):
                raise RunbookSourceError(f"{PATTERNS}: {identifier} has no title")
            if identifier.startswith("runbooks:") and not row.get("url"):
                raise RunbookSourceError(f"{PATTERNS}: {identifier} has no url")
            patterns[identifier] = row
    for identifier in DEFAULT_RELATED_PATTERNS:
        if identifier not in patterns:
            raise RunbookSourceError(f"{PATTERNS}: missing default related pattern {identifier}")

    notes = {}
    for path in sorted(name for name in files if posixpath.dirname(name) == NOTES and name.endswith(".json")):
        slug = PurePosixPath(path).stem
        if slug not in solutions:
            if slug in PACKAGE_ALIASES:
                raise RunbookSourceError(
                    f"{path}: notes filenames use package-folder slugs; "
                    f"use {NOTES}/{PACKAGE_ALIASES[slug]}.json"
                )
            raise RunbookSourceError(f"{path}: notes have no catalog package")
        solution = solutions[slug]
        entry = _json(root, path, files, required=True)
        level2 = _json(root, solution.architecture_source, files)
        declared = _declared_systems(solution, level2)
        _validate_notes(solution.name, entry, files, patterns, declared, root)
        notes[solution.name] = entry
    _validate_vertical_names(root, files, {solution.agent["category"] for solution in solutions.values()})
    return Library(root, files, catalog, solutions, patterns, notes)


def _present(value) -> bool:
    if value is None:
        return False
    if isinstance(value, float) and not math.isfinite(value):
        return False
    if isinstance(value, (str, list, tuple, dict)):
        return bool(value) and (not isinstance(value, str) or bool(value.strip()))
    return True


def _text(value, fallback: str = "Not recorded") -> str:
    if not _present(value):
        return fallback
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, dict):
        parts = [f"{_label(key)}: {_text(item)}" for key, item in value.items() if _present(item)]
        return "; ".join(parts) or fallback
    if isinstance(value, (list, tuple)):
        return "; ".join(_text(item) for item in value if _present(item)) or fallback
    text = str(value).strip()
    return fallback if text in {"None", "null", "nan", "{}", "[]"} else text


def _items(value) -> list:
    if not _present(value):
        return []
    return list(value) if isinstance(value, (list, tuple)) else [value]


def _object(value) -> dict:
    return value if isinstance(value, dict) else {}


def _label(value) -> str:
    text = str(value).replace("_", " ").strip()
    return text[:1].upper() + text[1:]


def _cell(value) -> str:
    text = _text(value)
    text = re.sub(r"(?<!\\)\|", r"\\|", text)
    return re.sub(r"\s*\n\s*", "<br>", text.replace("\r\n", "\n").replace("\r", "\n"))


def _table(headers, rows, missing: str) -> str:
    rows = list(rows)
    if not rows:
        return missing
    lines = [
        "|" + "".join(" " + _cell(header) + " |" if header != "" else " |" for header in headers),
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(_cell(value) for value in row) + " |" for row in rows)
    return "\n".join(lines)


def _bullets(value, missing: str, checklist: bool = False) -> str:
    items = [item for item in _items(value) if _present(item)]
    prefix = "- [ ] " if checklist else "- "
    return "\n".join(prefix + _text(item).replace("\n", "\n  ") for item in items) or missing


def _code(value, language: str = "text") -> str:
    body = _text(value)
    longest = max((len(m.group()) for m in re.finditer(r"`+", body)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}{language}\n{body}\n{fence}"


def _finish(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def _slug_heading(text: str) -> str:
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text.replace("`", "")).strip().lower()
    return "".join(
        character for character in text
        if unicodedata.category(character)[0] in "LN"
        or unicodedata.category(character) == "Mn" or character in " -_"
    ).replace(" ", "-")


def _visible_lines(text: str):
    fence = None
    for line in text.splitlines():
        marker = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if fence:
            yield line, False
            if marker and marker[1][0] == fence[0] and len(marker[1]) >= len(fence):
                fence = None
        elif marker:
            fence = marker[1]
            yield line, False
        else:
            yield line, True


def _section(text: str, title: str) -> str | None:
    lines = list(_visible_lines(text))
    for index, (line, visible) in enumerate(lines):
        match = _HEADING.match(line) if visible else None
        if match and match[2].casefold() == title.casefold():
            end = index + 1
            while end < len(lines):
                next_line, next_visible = lines[end]
                next_heading = _HEADING.match(next_line) if next_visible else None
                if next_heading and len(next_heading[1]) <= len(match[1]):
                    break
                end += 1
            return "\n".join(item[0] for item in lines[index + 1:end]).strip()
    return None


def _relative_url(library: Library, source: str, target: str, destination: str) -> str:
    if not target or target.startswith("//") or _SCHEME.match(target):
        return target
    split = urlsplit(target)
    decoded = unquote(split.path)
    resolved = (
        source if not decoded else
        posixpath.normpath(decoded.lstrip("/")) if decoded.startswith("/") else
        posixpath.normpath(posixpath.join(posixpath.dirname(source), decoded))
    )
    if resolved == ".." or resolved.startswith("../"):
        raise RunbookSourceError(f"{source}: copied link escapes repository: {target}")
    if resolved.endswith(".html"):
        if resolved not in library.files:
            raise RunbookSourceError(f"{source}: missing Pages target {resolved}")
        path = PAGES + quote(resolved, safe="/@-._~")
    else:
        path = quote(posixpath.relpath("/" + resolved, "/" + posixpath.dirname(destination)), safe="/@-._~")
        if decoded.endswith("/") and not path.endswith("/"):
            path += "/"
    return path + ("?" + split.query if split.query else "") + ("#" + split.fragment if split.fragment else "")


def _rebase_inline(line: str, transform) -> str:
    # A balanced scan keeps URLs with parentheses and optional link titles intact.
    output, cursor = [], 0
    while True:
        start = line.find("](", cursor)
        if start < 0:
            output.append(line[cursor:])
            break
        target_start = start + 2
        while target_start < len(line) and line[target_start].isspace():
            target_start += 1
        target_end = target_start
        if target_start < len(line) and line[target_start] == "<":
            target_start += 1
            target_end = line.find(">", target_start)
            if target_end < 0:
                output.append(line[cursor:])
                break
        else:
            depth = 0
            while target_end < len(line):
                character = line[target_end]
                if character == "\\":
                    target_end += 2
                    continue
                if character == "(":
                    depth += 1
                elif character == ")":
                    if depth == 0:
                        break
                    depth -= 1
                elif character.isspace() and depth == 0:
                    break
                target_end += 1
        if target_end <= target_start:
            output.append(line[cursor:start + 2])
            cursor = start + 2
            continue
        output.append(line[cursor:target_start])
        output.append(transform(line[target_start:target_end]))
        cursor = target_end
    return "".join(output)


def _mark_missing_links(library: Library, line: str, destination: str) -> str:
    def replace(match):
        target = match[2].strip("<>")
        if _SCHEME.match(target) or target.startswith("//"):
            return match[0]
        path = unquote(urlsplit(target).path)
        resolved = (
            destination if not path
            else posixpath.normpath(posixpath.join(posixpath.dirname(destination), path))
        )
        if library.exists(resolved):
            return match[0]
        return f"{match[1]} (missing source: `{resolved}`)"

    return re.sub(
        r"!?\[([^\]]+)\]\(\s*(<[^>]+>|[^\s)]+)(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)",
        replace, line,
    )


def _copy_markdown(library: Library, text: str, source: str, destination: str) -> str:
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    out = []
    for line, visible in _visible_lines(text):
        if not visible:
            out.append(line)
            continue
        match = _HEADING.match(line)
        if match:
            if len(match[1]) == 1:
                continue
            line = "#" * min(6, len(match[1]) + 1) + " " + match[2]
        transform = lambda target: _relative_url(library, source, target, destination)
        # Inline code is source text, not a Markdown link destination.
        segments = re.split(r"(`+[^`]*`+)", line)
        for index in range(0, len(segments), 2):
            segment = _rebase_inline(segments[index], transform)
            segment = re.sub(
                r"^(\s{0,3}\[[^\]]+\]:\s*)(<[^>]+>|\S+)",
                lambda m: m[1] + (
                    "<" + transform(m[2][1:-1]) + ">" if m[2].startswith("<") else transform(m[2])
                ), segment,
            )
            segment = re.sub(
                r"(\b(?:href|src)\s*=\s*)([\"'])(.*?)(\2)",
                lambda m: m[1] + m[2] + transform(m[3]) + m[4], segment, flags=re.I,
            )
            segments[index] = _mark_missing_links(library, segment, destination)
        out.append("".join(segments))
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def _body_sources(library: Library, document: str, text: str) -> set[str]:
    sources = set()
    def collect(target: str) -> str:
        target = target.strip("<>")
        if _learn_source(target):
            sources.add(target)
            return target
        parsed = urlsplit(target)
        if parsed.scheme or parsed.netloc:
            if target.startswith(PAGES):
                path = unquote(parsed.path.removeprefix("/aibast-agents-library/"))
            elif parsed.netloc == "raw.githubusercontent.com" and parsed.path.startswith("/microsoft/aibast-agents-library/main/"):
                path = unquote(parsed.path.removeprefix("/microsoft/aibast-agents-library/main/"))
            else:
                return target
        elif not parsed.path:
            return target
        else:
            path = posixpath.normpath(posixpath.join(posixpath.dirname(document), unquote(parsed.path)))
        if path in library.files or path.startswith("01-solutions/") and path.endswith(".md"):
            sources.add(path)
        return target
    for line, visible in _visible_lines(text):
        if not visible:
            continue
        line = re.sub(r"(`+).*?\1", "", line)
        _rebase_inline(line, collect)
        reference = re.match(r"^\s{0,3}\[[^\]]+\]:\s*(<[^>]+>|\S+)", line)
        if reference:
            collect(reference[1])
        for tag in re.findall(r"<[A-Za-z][^>]*>", line):
            for target in re.findall(r"\b(?:href|src)\s*=\s*[\"']([^\"']+)[\"']", tag, re.I):
                collect(target)
    return sources


