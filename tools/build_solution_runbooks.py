def _evidence_files(library: Library, solution: Solution) -> list[str]:
    return sorted({
        name for name in library.files
        if posixpath.dirname(name) == solution.path("evals")
        and (fnmatch.fnmatchcase(posixpath.basename(name), "*evidence*.json")
             or posixpath.basename(name) == "visual-checkpoints.json")
    })


def _recorded_fields(value, prefix: str = ""):
    if isinstance(value, dict):
        for key, item in sorted(value.items()):
            path = prefix + "." + key if prefix else key
            if (
                key in {"status", "verdict", "published"}
                or key.endswith("_status") or key.endswith("_verdict")
            ) and _present(item) and not isinstance(item, (dict, list)):
                yield path, _text(item)
            if isinstance(item, (dict, list)):
                yield from _recorded_fields(item, path)
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from _recorded_fields(item, f"{prefix}[{index}]")


def _manifest_references(doc: Document) -> list[dict]:
    data = doc.data(doc.solution.path("export-manifest.json"))
    return [item for item in _items(data.get("files")) if isinstance(item, dict)]


def _manifest_path(solution: Solution, value) -> str | None:
    if not isinstance(value, str) or not value:
        return None
    if value.startswith(("solutions/", "agents/", "tests/", "state/", "skills/", "docs/")):
        return value
    if _SCHEME.match(value) or value.startswith("/"):
        return None
    return posixpath.normpath(solution.path(value))


def _manual_knowledge(doc: Document) -> list[tuple[str, str]]:
    paths = {
        path: "Upload as synthetic knowledge"
        for path in doc.library.matching(doc.solution.path("manual/knowledge/*"))
    }
    for item in _manifest_references(doc):
        if "manual knowledge upload" in _text(item.get("use"), "").casefold():
            path = _manifest_path(doc.solution, item.get("path"))
            if path:
                paths[path] = _text(item["use"])
    return sorted(paths.items())


