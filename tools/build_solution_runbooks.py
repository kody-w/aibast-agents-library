def _stage(solution: Solution) -> str:
    return solution.stage + (f" / {solution.secondary_stage} (secondary)" if solution.secondary_stage else "")


def _groups(library: Library):
    verticals = sorted({solution.vertical for solution in library.solutions.values()})
    for vertical in verticals:
        yield vertical, sorted(
            (solution for solution in library.solutions.values() if solution.vertical == vertical),
            key=lambda solution: (solution.display_name.casefold(), solution.slug),
        )


