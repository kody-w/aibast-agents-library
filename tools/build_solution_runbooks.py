def _release_checklist(doc: Document) -> str:
    relative = "solutions/README.md"
    if relative not in doc.library.files:
        return doc.missing(relative)
    doc.source(relative)
    source = (doc.library.root / relative).read_text(encoding="utf-8")
    body = _section(source, "Release gate")
    if not body:
        return f"Source section “Release gate” is not present in {doc.link(relative)}."
    items = []
    active = False
    for line, visible in _visible_lines(body):
        if not visible:
            active = False
            continue
        match = re.match(r"^\d+[.)]\s+(.+)", line)
        if match:
            items.append(match[1])
            active = True
        elif active and line.startswith((" ", "\t")) and line.strip():
            items[-1] += " " + line.strip()
        else:
            active = False
    if not items:
        return f"No numbered release checks are present in {doc.link(relative, 'Release gate', 'release-gate')}."
    content = _bullets(items, "", checklist=True)
    return _copy_markdown(doc.library, content, relative, doc.path)


