def diagram_label_lines(label):
    return [html.unescape(part.replace("#quot;", '"')).strip() for part in re.split(r"<br\s*/?>", label, flags=re.I)]


def logical_node_roles(graph, context):
    boundaries = [key for key, label in graph.subgraphs.items() if label == "Synthetic demo boundary"]
    assert len(boundaries) == 1, f"{context}: synthetic boundary must occur exactly once"
    inside = {key for key, memberships in graph.membership.items() if boundaries[0] in memberships}
    agents = [key for key in inside if "GitHub Copilot harness" in graph.nodes[key]]
    skills = [key for key in inside if re.fullmatch(r"\d+ skills?", diagram_label_lines(graph.nodes[key])[0])]
    assert len(agents) == len(skills) == 1, f"{context}: agent and skills must be explicit inside the synthetic boundary"
    assert "n0" in graph.nodes and "n0" not in inside, f"{context}: blueprint channel node n0 must be outside the boundary"
    return agents[0], skills[0], inside - set(agents) - set(skills), set(graph.nodes) - inside - {"n0"}


