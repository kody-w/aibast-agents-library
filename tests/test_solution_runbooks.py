def markdown_record_headers(text, filename, links):
    rows = []
    heading = filename
    seen = Counter()
    lines = links.strip_code(text, inline=False).splitlines()
    for index, line in enumerate(lines[:-1]):
        match = HEADING.match(line)
        if match:
            heading = match[2]
        cells = [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
        separator = [
            cell.strip() for cell in re.split(r"(?<!\\)\|", lines[index + 1].strip().strip("|"))
        ]
        if "|" not in line or len(cells) != len(separator) or not all(
            re.fullmatch(r":?-{3,}:?", cell) for cell in separator
        ):
            continue
        seen[heading] += 1
        entity = heading + (f" (table {seen[heading]})" if seen[heading] > 1 else "")
        rows.append((entity, cells))
    return rows


