def validate_generated_document(path, text, links):
    assert text.startswith(MARKER + "\n"), f"{path}: generated marker must be the first line"
    assert "\r" not in text and text.endswith("\n") and not text.endswith("\n\n"), (
        f"{path}: require LF endings and exactly one trailing newline"
    )
    visible = links.strip_code(text, inline=False).splitlines()
    headings = [(index, match[1], match[2]) for index, line in enumerate(visible) if (match := HEADING.match(line))]
    artifact = path.split("/", 2)[2] if path.count("/") >= 2 else None
    if artifact in SECTIONS:
        actual = tuple(title for _, level, title in headings if level == "##")
        assert actual == SECTIONS[artifact], f"{path}: H2 order/titles {actual!r} != {SECTIONS[artifact]!r}"
    content_lines = links.strip_code(text, inline=False, fence_fill="\x00code").splitlines()
    for index, level, title in headings:
        stop = next((i for i, other, _ in headings if i > index and len(other) <= len(level)), len(content_lines))
        body = "\n".join(content_lines[index + 1:stop])
        body = re.sub(r"(?m)^\s*(?:[-*_]{3,}|`{3,}|~{3,})\s*$", "", body)
        assert body.strip(), f"{path}: empty section {title!r}"
    for number, line in enumerate(links.strip_code(text).splitlines(), 1):
        match = LEAK.search(line)
        assert match is None, f"{path}:{number}: placeholder/value leak {match[0]!r}" if match else ""


