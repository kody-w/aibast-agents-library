def authored_rapp_prose(text, links):
    prose = visible_prose(links.strip_code(text), links)
    prose = re.sub(r"https?://\S+", "", prose)
    prose = re.sub(r"(?:[\w.-]+[/\\])*[\w.-]+\.(?:md|py|html|json|ya?ml)\b", "", prose, flags=re.I)
    return re.sub(r"\s+", " ", prose).strip()


