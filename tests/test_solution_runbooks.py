def parse_mermaid(block, context):
    lines = [line.strip() for line in block.splitlines() if line.strip()]
    assert lines and lines[0] == "flowchart LR", f"{context}: Mermaid must start with flowchart LR"
    nodes, subgraphs, membership, stack, edges = {}, {}, {}, [], []
    identifier = r"[A-Za-z_][A-Za-z0-9_]*"
    for line in lines[1:]:
        node = re.fullmatch(r'(' + identifier + r')\["([^"\n]*)"\]', line)
        subgraph = re.fullmatch(r'subgraph\s+(' + identifier + r')\s*\["([^"\n]+)"\]', line)
        edge = re.fullmatch(
            r"(" + identifier + r")\s*(-->|-\.->)\s*"
            r"(?:\|(?:\"[^\"\n]*\"|[^|\"\n]+)\|\s*)?(" + identifier + r")",
            line,
        )
        assert node or edge or subgraph or line == "end", f"{context}: malformed Mermaid line: {line!r}"
        if line == "end":
            assert stack, f"{context}: unmatched Mermaid end"
            stack.pop()
        elif subgraph:
            assert subgraph[1] not in nodes.keys() | subgraphs.keys(), f"{context}: duplicate Mermaid node {subgraph[1]}"
            subgraphs[subgraph[1]] = subgraph[2]
            stack.append(subgraph[1])
        elif node:
            assert node[1] not in nodes.keys() | subgraphs.keys(), f"{context}: duplicate Mermaid node {node[1]}"
            nodes[node[1]] = node[2]
            membership[node[1]] = tuple(stack)
        else:
            edges.append((edge[1], edge[2], edge[3]))
    assert not stack, f"{context}: unclosed Mermaid subgraph: {stack}"
    assert nodes, f"{context}: Mermaid diagram has no nodes"
    for start, _, end in edges:
        assert {start, end} <= nodes.keys() | subgraphs.keys(), f"{context}: Mermaid edge uses undefined node: {start} -> {end}"
    return SimpleNamespace(nodes=nodes, subgraphs=subgraphs, membership=membership, edges=edges, block=block)


def validate_mermaid(text, context):
    blocks = re.findall(r"^```mermaid[ \t]*\n(.*?)^```[ \t]*$", text, re.M | re.S)
    assert blocks, f"{context}: no Mermaid diagram was measured"
    for block in blocks:
        parse_mermaid(block, context)


