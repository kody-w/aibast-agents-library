def validate_identity(catalog, packages, aliases, drafts):
    assert catalog, "Identity join cannot measure an empty catalogue"
    resolved = {}
    for key in sorted(catalog):
        assert key.startswith("@aibast-agents-library/"), f"Noncanonical catalogue key: {key}"
        name = key.split("/")[-1]
        matches = sorted(slug for slug, identity in packages.items() if identity == key)
        assert len(matches) == 1, f"{key}: expected exactly one deployment.json name match, found {matches}"
        slug = matches[0]
        expected = aliases.get(name, name)
        assert slug == expected, f"{key}: package slug {slug!r} != canonical/aliased {expected!r}"
        resolved[key] = slug
    orphans = set(packages) - set(resolved.values()) - set(drafts)
    assert not orphans, f"Orphan package directories: {sorted(orphans)}"
    for name, slug in aliases.items():
        key = "@aibast-agents-library/" + name
        assert key in catalog and name != slug and resolved.get(key) == slug, (
            f"Stale alias: {name!r} -> {slug!r}"
        )
    for slug, reason in drafts.items():
        assert slug in packages and slug not in resolved.values(), f"Stale draft allowlist entry: {slug}"
        assert isinstance(reason, str) and reason.strip(), f"{slug}: draft allowlist needs a reason"
    return resolved


def validate_patterns(data, readme, defaults):
    assert data.get("schema") == "aibast-pattern-index/1.0", "patterns.json: unsupported schema"
    assert isinstance(data.get("source"), str) and data["source"].strip(), "patterns.json: source must be text"
    ids = []
    for group, prefix, count in (("aibast_patterns", "aibast:", 8), ("runbooks_patterns", "runbooks:", 17)):
        entries = data.get(group)
        assert isinstance(entries, list), f"patterns.json: {group} must be a list"
        for entry in entries:
            assert isinstance(entry, dict), f"{group}: entry must be an object"
            identity = entry.get("id")
            assert isinstance(identity, str) and identity.startswith(prefix) and len(identity) > len(prefix), (
                f"{group}: invalid id {identity!r}"
            )
            assert identity not in ids, f"Duplicate pattern id: {identity}"
            ids.append(identity)
            for field in ("title", "folder") if prefix == "aibast:" else ("title", "url", "runbook_url"):
                assert isinstance(entry.get(field), str) and entry[field].strip(), f"{identity}: {field} must be text"
            assert entry["title"] in readme, f"02-patterns/README.md missing title: {entry['title']}"
            if prefix == "aibast:":
                assert entry.get("status") == "Planned", f"{identity}: native pattern must be Planned"
            else:
                for field in ("url", "runbook_url"):
                    assert re.fullmatch(
                        r"https://github\.com/microsoft/ai-agent-runbooks/blob/main/02-patterns/[^?#]+\.md",
                        entry[field],
                    ), f"{identity}: invalid {field}: {entry[field]!r}"
        assert len(entries) == count, f"{group}: expected {count} patterns, found {len(entries)}"
    assert set(defaults) <= set(ids), f"Unknown default pattern ids: {sorted(set(defaults) - set(ids))}"
    return set(ids)


def validate_note_source(source, files, context):
    assert isinstance(source, str) and source.strip(), f"{context}: source must be nonempty text"
    url = urlsplit(source)
    decoded = unquote(source)
    if url.scheme or url.netloc:
        assert (
            url.scheme == "https" and url.netloc == "learn.microsoft.com"
            and unquote(url.path).startswith("/en-us/") and unquote(url.path) != "/en-us/"
            and ".." not in decoded
        ), f"{context}: source must be a specific Microsoft Learn HTTPS URL under /en-us/ without '..': {source}"
    else:
        assert not PurePosixPath(source).is_absolute() and ".." not in PurePosixPath(decoded).parts, (
            f"{context}: notes source must be repository-relative: {source}"
        )
        assert source in files, f"{context}: missing notes source: {source}"


def validate_notes(data, catalog, pattern_ids, files):
    assert data.get("schema") == "aibast-solution-runbook-notes/1.0", "runbook-notes.json: unsupported schema"
    assert isinstance(data.get("source"), str) and data["source"].strip(), "runbook-notes.json: source must be text"
    notes = data.get("solutions")
    assert isinstance(notes, dict), "runbook-notes.json: solutions must be an object"
    assert set(notes) <= set(catalog), f"Unknown notes catalogue keys: {sorted(set(notes) - set(catalog))}"
    string_lists = {"scope_in", "scope_out", "qualification_checklist", "related_patterns", "sources", "never_do"}
    object_lists = {
        "target_users": {"role", "need"}, "what_goes_wrong": {"issue", "response"},
        "delivery_roles": {"role", "responsibility"}, "prerequisites": {"item", "detail"},
        "go_no_go": {"criterion", "threshold"}, "boundary_tests": {"prompt", "expected"},
        "design_decisions": {"decision", "reason"}, "production_hardening": {"area", "action", "owner"},
    }
    item_sources = {"design_decisions", "go_no_go", "boundary_tests", "production_hardening"}
    allowed = string_lists | set(object_lists) | {"phase_exit_criteria"}

    def valid_text(value, context):
        assert isinstance(value, str) and value.strip(), f"{context}: expected nonempty text"
        assert value.strip().casefold() not in SENTINELS, f"{context}: sentinel string {value!r}"

    for key, entry in notes.items():
        assert isinstance(entry, dict), f"{key}: notes must be an object"
        assert not set(entry) - allowed, f"{key}: unknown notes fields {sorted(set(entry) - allowed)}"
        if set(entry) - {"sources"}:
            assert entry.get("sources"), f"{key}: sources required when another notes field is present"
        for field, values in entry.items():
            if field == "phase_exit_criteria":
                assert isinstance(values, dict) and set(values) == set(PHASE_KEYS), (
                    f"{key}.{field}: expected phase_1 through phase_5"
                )
                for phase, criteria in values.items():
                    assert isinstance(criteria, list) and criteria, f"{key}.{field}.{phase}: expected a nonempty list"
                    for criterion in criteria:
                        context = f"{key}.{field}.{phase}"
                        if isinstance(criterion, dict):
                            assert set(criterion) == {"text", "source"}, f"{context}: expected text/source object"
                            valid_text(criterion["text"], context)
                            validate_note_source(criterion["source"], files, context)
                        else:
                            valid_text(criterion, context)
                continue
            assert isinstance(values, list), f"{key}.{field}: expected list"
            for value in values:
                if field in string_lists:
                    valid_text(value, f"{key}.{field}")
                else:
                    expected = object_lists[field]
                    optional = {"source"} if field in item_sources else set()
                    assert isinstance(value, dict) and expected <= set(value) <= expected | optional, (
                        f"{key}.{field}: expected objects with {sorted(object_lists[field])}"
                    )
                    for name, text in value.items():
                        valid_text(text, f"{key}.{field}")
                        if name == "source":
                            validate_note_source(text, files, f"{key}.{field}.source")
        for source in entry.get("sources", []):
            validate_note_source(source, files, key)
        roles = {item["role"] for item in entry.get("delivery_roles", [])}
        for step in entry.get("production_hardening", []):
            assert step["owner"] in roles, f"{key}.production_hardening: unknown delivery_roles owner {step['owner']!r}"
        for identity in entry.get("related_patterns", []):
            assert identity in pattern_ids, f"{key}: unknown pattern id: {identity}"


def validate_journeys(catalog, stages, normalize):
    assert isinstance(stages, tuple) and stages, "JOURNEY_STAGES must be a nonempty tuple"
    assert stages == tuple(sorted(set(stages))), "JOURNEY_STAGES must be sorted and unique"
    primaries = set()
