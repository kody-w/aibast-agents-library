    def test_renderer_escapes_url_ampersands_once_and_renders_nested_headings_safely(self):
        pipeline = load_pipeline()
        linked = pipeline.inline_markdown("[Reference](https://example.com/path?a=1&b=2)")
        self.assertIn('href="https://example.com/path?a=1&amp;b=2"', linked)
        self.assertNotIn("&amp;amp;", linked)
        rendered = pipeline.render_markdown(
            "## Technical approach\n\n"
            "A safe section.\n\n"
            "### Detail <script>alert(1)</script>\n\n"
            "A safe subsection."
        )
        self.assertIn("<h3>Technical approach</h3>", rendered)
        self.assertIn("<h4>Detail &lt;script&gt;alert(1)&lt;/script&gt;</h4>", rendered)
        self.assertNotIn("<p>###", rendered)

    def test_arbitrary_legacy_html_is_rejected_and_not_raw_rendered(self):
        pipeline = load_pipeline()
        metadata = {
            "schema": "aibast-blog/1.0",
            "contribution_type": "blog_post",
            "slug": "untrusted-legacy-html",
            "title": "Untrusted legacy HTML mutation",
            "author": "Alex Rivera (@alex-rivera)",
            "date": "2026-08-15",
            "status": "published",
            "publication": "generated-from-canonical-submission",
            "legacy_html": True,
            "summary": "A sufficiently detailed concrete problem summary for the generated staging preview.",
            "audience": "Solution architects reviewing a staged contribution workflow.",
            "prerequisites": "A local checkout, GitHub access, and a reviewed generated submission.",
            "applicability": "Applies to staging contributions that need a generated public review path.",
            "support_boundary": "Schema validation only; it does not grant production support or publish content.",
            "limitations": "This mutation fixture validates raw HTML restrictions and does not prove production publishing or tenant compatibility.",
            "tags": ["staging", "security"],
            "evidence": [{"label": "Evidence", "url": "https://example.com/evidence"}],
            "links": [{"label": "Source", "url": "https://example.com/source"}],
        }
        post = "<img src=x onerror=alert(1)> " + " ".join(["history"] * 260)
        submission = pipeline.Submission(Path("submissions/blog/untrusted-legacy-html"), metadata, post)
        errors = pipeline.validate_submission(submission)
        self.assertTrue(any("restricted to migrated historical" in error for error in errors), errors)
        self.assertTrue(any("active content" in error for error in errors), errors)
        rendered = pipeline.render_submission(submission)
        self.assertIn("&lt;img", rendered)
        self.assertNotIn("<img src=x", rendered)

