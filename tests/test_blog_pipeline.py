    def test_contribution_handoff_uses_real_newlines_and_distribution_owner(self):
        library = (ROOT / "library.html").read_text(encoding="utf-8")
        literal_backslash_join = re.compile(r"""\.join\(\s*["']\\\\n["']\s*\)""")
        self.assertIsNone(literal_backslash_join.search(library))
        self.assertIn('].join("\\n"));', library)
        self.assertIn("const DISTRIBUTION_OWNER = location.hostname.endsWith", library)
        self.assertIn("https://github.com/${DISTRIBUTION_OWNER}/${REPO}/issues/new", library)
        self.assertIn("https://github.com/${DISTRIBUTION_OWNER}/${REPO}/discussions/new", library)
        self.assertNotIn("https://github.com/${OWNER}/${REPO}/issues/new", library)
        self.assertNotIn("https://github.com/${OWNER}/${REPO}/discussions/new", library)

