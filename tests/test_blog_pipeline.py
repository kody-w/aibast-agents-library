"""Focused contracts for canonical, generated blog content."""

from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PIPELINE = ROOT / "scripts" / "blog_pipeline.py"
SUBMISSIONS = ROOT / "submissions" / "blog"


def load_pipeline():
    spec = importlib.util.spec_from_file_location("blog_pipeline", PIPELINE)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class BlogPipelineTests(unittest.TestCase):
    def test_canonical_submissions_validate(self):
        pipeline = load_pipeline()
        submissions, errors = pipeline.validate_all(SUBMISSIONS)
        self.assertEqual([], errors)
        self.assertGreaterEqual(len(submissions), 3)

    def test_generated_blog_has_no_drift(self):
        result = subprocess.run(
            [sys.executable, str(PIPELINE), "check"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        blog = (ROOT / "blog.html").read_text(encoding="utf-8")
        self.assertIn("<!-- blog-posts:begin -->", blog)
        self.assertIn("<!-- Generated by scripts/blog_pipeline.py; do not hand-edit. -->", blog)
        self.assertIn('href="#device-code-login-race"', blog)
        self.assertIn("Applicability", blog)
        self.assertIn("Support boundary", blog)
        self.assertNotIn("<p># How a background thread", blog)
        self.assertNotIn("<strong>Try this:</strong> </p>", blog)

    def test_renderer_changes_a_stale_generated_region(self):
        pipeline = load_pipeline()
        submissions, errors = pipeline.validate_all(SUBMISSIONS)
        self.assertEqual([], errors)
        stale = f"before\n{pipeline.BEGIN}\nstale\n{pipeline.END}\nafter\n"
        rendered = pipeline.replace_region(stale, pipeline.render_region(submissions))
        self.assertNotEqual(stale, rendered)
        self.assertIn("Generated by scripts/blog_pipeline.py", rendered)

